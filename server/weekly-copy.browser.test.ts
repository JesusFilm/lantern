import assert from 'node:assert/strict';
import { test } from 'node:test';
import { chromium, expect } from '@playwright/test';
import { createServer } from 'vite';
import { coachingFixture } from './coach-test-support.js';

test('members enter each week’s goals by hand without a copy control or carried-over work', async t => {
  const f = await coachingFixture();
  let vite: Awaited<ReturnType<typeof createServer>> | undefined;
  let browser: Awaited<ReturnType<typeof chromium.launch>> | undefined;
  t.after(async () => { await browser?.close(); await vite?.close(); await f.close(); });
  const previous = '/api/weeks/2026-11-16', current = '/api/weeks/2026-11-23';
  await f.request('member', previous + '/plans', 'POST', { version: 0, goals: [{ text: 'Last week’s work', links: [] }] });
  const history = await (await f.request('member', previous)).json();
  vite = await createServer({ server: { middlewareMode: { server: f.server }, hmr: { server: f.server } }, appType: 'spa' });
  f.app.use(vite.middlewares);
  browser = await chromium.launch();
  const context = await browser.newContext({ timezoneId: 'Pacific/Auckland' });
  await context.clock.setFixedTime(new Date('2026-11-25T10:00:00+13:00'));
  await context.addCookies([{ name: 'lantern-session', value: 'member', url: f.origin }]);
  const page = await context.newPage(); page.setDefaultTimeout(5000);
  await page.goto(f.origin + '/?page=week');await page.getByRole('tab', { name: 'Goals', exact: true }).click();
  await expect(page.getByRole('region', { name: 'Weekly goals', exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Copy last week’s goals', exact: true })).toHaveCount(0);
  await expect(page.getByText(/Saves automatically\.|Daily updates are visible/)).toHaveCount(0);
  const goal = page.getByRole('textbox', { name: 'Weekly goal 1', exact: true });
  await expect(goal).toHaveValue('');
  await goal.fill('Write this week’s plan deliberately');
  await expect.poll(async () => (await (await f.request('member', current)).json()).plans.at(-1)?.goals[0].text).toBe('Write this week’s plan deliberately');
  await page.reload();await page.getByRole('tab', { name: 'Goals', exact: true }).click(); await expect(goal).toHaveValue('Write this week’s plan deliberately');
  await page.getByRole('tab', { name: 'Updates', exact: true }).click();
  await page.getByRole('button', { name: 'Next week', exact: true }).click();await page.getByRole('tab', { name: 'Goals', exact: true }).click();
  await expect(goal).toHaveValue('');
  await expect(page.getByRole('button', { name: 'Copy last week’s goals', exact: true })).toHaveCount(0);
  assert.deepEqual(await (await f.request('member', previous)).json(), history);
  assert.deepEqual((await (await f.request('peer', current)).json()).plans, []);
});
