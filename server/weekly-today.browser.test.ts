test('help icons open and dismiss by touch without overlapping their headings', async () => {
  const f=await coachingFixture();
  const vite=await createServer({server:{middlewareMode:{server:f.server},hmr:{server:f.server}},appType:'spa'});f.app.use(vite.middlewares);
  const browser=await chromium.launch();
  try {
    const context=await browser.newContext({hasTouch:true,isMobile:true,viewport:{width:390,height:844},timezoneId:'Pacific/Auckland'});
    await context.clock.setFixedTime(new Date('2026-11-19T10:00:00+13:00'));
    await context.addCookies([{name:'lantern-session',value:'member',url:f.origin}]);
    const page=await context.newPage();await page.goto(f.origin+'/?page=week');
    for(const [heading,title] of [['Today’s update','What makes a useful daily update?'],['Weekly goals','What makes a useful weekly goal?']]) {
      if(heading==='Weekly goals') await page.getByRole('tab', { name: 'Goals', exact: true }).tap();
      const icon=page.getByRole('button',{name:title,exact:true}), help=page.getByRole('dialog',{name:title,exact:true});
      await icon.tap();await expect(help).toBeVisible();
      await icon.tap();await expect(help).not.toBeVisible();
      const [text,button]=await Promise.all([page.getByRole('heading',{name:heading,exact:true}).boundingBox(),icon.boundingBox()]);
      assert.ok(text && button && button.x>=text.x+text.width,'The icon does not overlap the heading');
    }
  } finally {await browser.close();await vite.close();await f.close();}
});
