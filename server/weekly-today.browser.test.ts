import assert from 'node:assert/strict';
import { test } from 'node:test';
import { chromium, expect } from '@playwright/test';
import { createServer } from 'vite';
import { coachingFixture } from './coach-test-support.js';

test('today stays editable after saving and reflects live goals while past days retain their snapshots', async () => {
  const f=await coachingFixture(), path='/api/weeks/2026-11-16';
  const first=await(await f.request('member',path+'/plans','POST',{version:0,goals:[{text:'Original goal',links:[]}]})).json();
  const goalId=first.plans[0].goals[0].id;
  const flags=[{goalId,status:'blocked'}];
  for(const [date,body] of [['2026-11-16','Monday’s notes'],['2026-11-17','Tuesday’s notes'],['2026-11-18','Yesterday’s notes'],['2026-11-19','Today’s notes']]) await f.request('member',path+'/updates','POST',{date,body,planVersion:1,goalStatuses:flags});
  const vite=await createServer({server:{middlewareMode:{server:f.server},hmr:{server:f.server}},appType:'spa'});f.app.use(vite.middlewares);
  const browser=await chromium.launch();
  try{
    const context=await browser.newContext({timezoneId:'Pacific/Auckland'});await context.clock.setFixedTime(new Date('2026-11-19T10:00:00+13:00'));
    await context.addCookies([{name:'lantern-session',value:'member',url:f.origin}]);const page=await context.newPage();page.setDefaultTimeout(5000);
    await page.goto(f.origin+'/?page=week');
    const today=page.getByRole('region',{name:'Daily update',exact:true}), text=today.getByRole('textbox',{name:'Daily update',exact:true});
    await expect(today.getByRole('heading',{name:'Thursday, 19 Nov',exact:true})).toBeVisible();
    await expect(text).toHaveValue('Today’s notes');await expect(text).toBeEditable();
    await expect(page.getByRole('button',{name:'Edit update',exact:true})).toHaveCount(0);
    const past=page.locator('details.week-day-entry');await expect(past).toHaveCount(3);
    await expect(past.locator('summary')).toHaveText(['Wednesday, 18 Nov','Tuesday, 17 Nov','Monday, 16 Nov']);
    const boxes=await Promise.all([today.boundingBox(),past.nth(0).boundingBox(),past.nth(1).boundingBox()]);
    assert.ok(boxes.every(Boolean));
    assert.ok(Math.abs((boxes[1]!.y-boxes[0]!.y-boxes[0]!.height)-(boxes[2]!.y-boxes[1]!.y-boxes[1]!.height))<1,'Today and previous days have equal spacing');
    await page.getByRole('textbox',{name:'Weekly goal 1',exact:true}).fill('Renamed goal');
    await page.getByRole('group',{name:'Status for Renamed goal',exact:true}).getByRole('radio',{name:'Done',exact:true}).check();
    await expect(today.getByText('Renamed goal',{exact:true})).toBeVisible();await expect(today.getByText('Done',{exact:true})).toBeVisible();
    await past.first().locator('summary').click();await expect(past.first().getByText('Original goal',{exact:true})).toBeVisible();await expect(past.first().getByText('Blocked',{exact:true})).toBeVisible();
    await text.fill('Updated today’s notes');
    await expect(page.getByRole('button',{name:"Save today's update",exact:true})).toHaveCount(0);
    await expect.poll(async () => (await(await f.request('member',path)).json()).updates.at(-1)?.body).toBe('Updated today’s notes');
    await expect(text).toBeEditable();
    await expect(today.locator('summary')).toHaveCount(0);
    const record=await(await f.request('member',path)).json();assert.equal(record.updates.length,4);assert.equal(record.updates[3].goalStatuses[0].status,'done');assert.equal(record.updates[2].body,'Yesterday’s notes');
    await page.getByRole('button',{name:'Add Goal',exact:true}).click();
    await page.getByRole('textbox',{name:'Weekly goal 2',exact:true}).fill('Prepare the demo');
    await expect(page.getByRole('group',{name:'Status for Prepare the demo',exact:true}).getByRole('radio',{name:'On track',exact:true})).not.toBeChecked();
    await page.getByRole('group',{name:'Status for Prepare the demo',exact:true}).getByRole('radio',{name:'On track',exact:true}).check();
    const added=today.getByRole('listitem').filter({hasText:'Prepare the demo'});
    await expect(added.getByText('On track',{exact:true})).toBeVisible();
    await expect.poll(async () => (await(await f.request('member',path)).json()).updates.at(-1)?.goalStatuses.map((flag: {status: string}) => flag.status)).toEqual(['done','on-track']);
    await page.reload();await expect(text).toHaveValue('Updated today’s notes');await expect(text).toBeEditable();await expect(today.getByText('Done',{exact:true})).toBeVisible();
    await expect(today.getByRole('listitem').filter({hasText:'Prepare the demo'}).getByText('On track',{exact:true})).toBeVisible();
    await page.route('**/api/weeks/*/updates', route => route.fulfill({status:503,json:{error:'Could not save your update.'}}));
    await text.fill('Keep these notes after a failed save');
    await expect(today.getByRole('alert')).toContainText('Could not save your update.');
    await expect(text).toHaveValue('Keep these notes after a failed save');
    await page.unroute('**/api/weeks/*/updates');
    let release!: () => void;
    const held = new Promise<void>(resolve => { release = resolve; });
    let started!: () => void;
    const pending = new Promise<void>(resolve => { started = resolve; });
    await page.route('**/api/weeks/*/updates', async route => { started(); await held; await route.continue(); });
    await today.getByRole('button',{name:'Retry saving update',exact:true}).click();
    await pending;
    await expect(text).toBeEditable();
    await text.fill('Latest notes typed while saving');
    await page.getByRole('group',{name:'Status for Prepare the demo',exact:true}).getByRole('radio',{name:'At risk',exact:true}).check();
    release();
    await expect.poll(async () => {
      const update=(await(await f.request('member',path)).json()).updates.at(-1);
      return {body:update.body,status:update.goalStatuses[1].status};
    }).toEqual({body:'Latest notes typed while saving',status:'at-risk'});
    await page.reload();await expect(text).toHaveValue('Latest notes typed while saving');
    await page.setViewportSize({width:320,height:844});
    assert.equal(await page.evaluate('document.documentElement.scrollWidth > innerWidth'),false);
  }finally{await browser.close();await vite.close();await f.close();}
});
